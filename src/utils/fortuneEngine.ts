export const areaText = (
  a: FArea,
  stars: number,
  p: Period,
  pool?: import('./fortuneDB').TextPool,
  birthKey?: string,
): string => {
  if (pool && birthKey) {
    const texts = pool.get(`${a}-${p}-${stars}`);
    if (texts && texts.length > 0) return texts[pickIdx(p, birthKey, texts.length)];
  }
  return TEXTS[a][p][stars];
};

