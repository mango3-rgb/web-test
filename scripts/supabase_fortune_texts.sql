-- ─── 1. 테이블 생성 ─────────────────────────────────
CREATE TABLE IF NOT EXISTS mystic_fortune_texts (
  id         UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
  area       TEXT         NOT NULL,
  period     TEXT         NOT NULL,
  stars      INT          NOT NULL,
  text_ko    TEXT         NOT NULL,
  sort_order INT          DEFAULT 0,
  created_at TIMESTAMPTZ  DEFAULT now(),
  CONSTRAINT chk_area   CHECK (area   IN ('money','love','career','health','overview')),
  CONSTRAINT chk_period CHECK (period IN ('daily','monthly','yearly','early','middle','late')),
  CONSTRAINT chk_stars  CHECK (stars BETWEEN 0 AND 5)
);

-- ─── 2. 인덱스 ──────────────────────────────────────
CREATE INDEX IF NOT EXISTS idx_fortune_texts_lookup
  ON mystic_fortune_texts (area, period, stars, sort_order);

-- ─── 3. RLS ─────────────────────────────────────────
ALTER TABLE mystic_fortune_texts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public read fortune texts" ON mystic_fortune_texts;
CREATE POLICY "public read fortune texts"
  ON mystic_fortune_texts FOR SELECT USING (true);

